# ==================== 主程序：把妹大师 V20.0 ====================

class PickupMaster:
    """把妹大师 V20.0 - 专业版"""
    
    def __init__(self):
        self.attraction = ATTRACTION_BUILDING
        self.opening = OPENING_LINES
        self.escalation = CHAT_ESCALATION
        self.dating = DATING_SKILLS
        self.physical = PHYSICAL_ESCALATION
        self.relationship = RELATIONSHIP_CONFIRMATION
        self.maintenance = LONG_TERM_MAINTENANCE
        self.cases = CASE_STUDIES
    
    def get_opening_line(self, category: str, scenario: str = None) -> Dict:
        """获取开场白"""
        if category not in self.opening["微信开场白库"]:
            return {"error": "未知类别"}
        
        templates = self.opening["微信开场白库"][category]
        
        if scenario:
            for t in templates:
                if scenario in t["场景"]:
                    return t
        
        return random.choice(templates)
    
    def get_chat_technique(self, category: str, technique: str = None) -> Dict:
        """获取聊天技巧"""
        if category not in self.escalation:
            return {"error": "未知类别"}
        
        techniques = self.escalation[category]
        
        if technique:
            for key in techniques:
                if technique in key:
                    return random.choice(techniques[key])
        
        # 随机返回一个类别
        cat = random.choice(list(techniques.keys()))
        return random.choice(techniques[cat])
    
    def get_date_advice(self, stage: str) -> Dict:
        """获取约会建议"""
        return self.dating.get(stage, {})
    
    def get_physical_guidance(self, level: str = "1") -> Dict:
        """获取肢体接触指导"""
        level_map = {
            "1": "安全接触",
            "2": "友好接触",
            "3": "暧昧接触",
            "4": "亲密接触",
            "5": "确定关系",
        }
        level_name = level_map.get(level, "安全接触")
        return self.physical["肢体接触进阶"].get(level_name, {})
    
    def analyze_situation(self, chat_history: str, date_count: int, physical_level: int) -> Dict:
        """
        分析当前关系阶段
        
        Args:
            chat_history: 聊天记录
            date_count: 约会次数
            physical_level: 肢体接触等级 (1-5)
        
        Returns:
            分析结果
        """
        # 判断阶段
        if date_count == 0:
            stage = "搭讪开场"
            advice = "先建立吸引力，不要急于邀约"
        elif date_count < 3:
            stage = "约会初期"
            advice = "继续升温关系，可以尝试轻微肢体接触"
        elif date_count < 5:
            stage = "暧昧期"
            advice = "可以增加肢体接触，准备表白"
        else:
            stage = "表白期"
            advice = "找合适时机表白，确定关系"
        
        return {
            "当前阶段": stage,
            "约会次数": date_count,
            "肢体等级": physical_level,
            "建议": advice,
        }
    
    def get_case_study(self, success: bool = True) -> Dict:
        """获取案例学习"""
        category = "成功案例" if success else "失败案例"
        cases = self.cases[category]
        case_name = random.choice(list(cases.keys()))
        return cases[case_name]
    
    def get_daily_tip(self) -> Dict:
        """获取每日技巧"""
        categories = [
            ("形象打造", self.attraction["形象打造"]),
            ("开场白", self.opening["微信开场白库"]),
            ("聊天升温", self.escalation),
            ("约会技巧", self.dating),
            ("肢体接触", self.physical),
        ]
        
        cat_name, cat_content = random.choice(categories)
        
        # 随机返回一个技巧
        if isinstance(cat_content, dict):
            key = random.choice(list(cat_content.keys()))
            if isinstance(cat_content[key], dict):
                sub_key = random.choice(list(cat_content[key].keys()))
                tip = random.choice(cat_content[key][sub_key])
            else:
                tip = random.choice(cat_content[key])
        else:
            tip = random.choice(cat_content)
        
        return {
            "类别": cat_name,
            "技巧": tip,
        }


