    def __init__(self, api_key: str = "", log_callback: Optional[Callable[[str], None]] = None):
        self.api_key = api_key
        self.log_callback = log_callback

    def _log(self, msg: str) -> None:
        """记录日志"""
        if self.log_callback:
            self.log_callback(msg)

    def detect_intent(self, message: str) -> str:
        """检测消息意图"""
        message = message.lower()
        for intent, keywords in self.INTENT_KEYWORDS.items():
            for kw in keywords:
                if kw in message:
                    return intent
        return "default"

    def generate_local_reply(self, message: str, relation: str, style: str = "稳妥版") -> Tuple[List[str], str]:
        """生成本地回复"""
        intent = self.detect_intent(message)
        templates = self.TEMPLATES.get(relation, self.TEMPLATES["朋友"])
        intent_templates = templates.get(intent, templates["default"])
        replies = intent_templates.get(style, intent_templates["稳妥版"])
        return replies, f"[本地模式] 意图:{intent}, 风格:{style}"

    def _parse_ai_response(self, content: str) -> List[str]:
        """
        V8.2 优化：解析 AI 返回内容
        策略 1: 提取引号内句子
        策略 2: 按行分割
        策略 3: 按句号分割
        """
        if not content:
            return []

        replies: List[str] = []

        # 策略 1: 提取被引号包裹的完整句子
        for quote in ['"', '"', "'", '「', '」', '『', '』']:
            pattern = f'{quote}([^{quote}]{{6,20}}){quote}'
            matches = re.findall(pattern, content)
            for match in matches:
                if match and not any(sw in match for sw in self.SKIP_WORDS):
                    replies.append(match.strip())

        # 策略 2: 按行分割
        if len(replies) < 2:
            for line in content.split('\n'):
                line = line.strip()
                if not line or any(sw in line for sw in self.SKIP_WORDS):
                    continue

                # 清理编号前缀和标记
                line = self._clean_line(line)

                if 6 <= len(line) <= 20 and not line.isdigit():
                    replies.append(line)

        # 策略 3: 按句号分割
        if len(replies) < 2:
            for part in re.split(r'[。;；]', content):
                part = part.strip()
                if 6 <= len(part) <= 20 and not any(sw in part for sw in self.SKIP_WORDS) and not part.isdigit():
                    replies.append(part)

        # 去重并限制 3 条
        seen: set = set()
        unique_replies: List[str] = []
        for r in replies:
            if r not in seen and 6 <= len(r) <= 20:
                seen.add(r)
                unique_replies.append(r)

        return unique_replies[:3]

    def _clean_line(self, line: str) -> str:
        """清理行首编号和标记"""
        line = re.sub(r'^[\d 一二三四五六七八九十百千万]+[.、:：)\]】}]+', '', line)
        line = re.sub(r'^[①②③④⑤⑥⑦⑧⑨⑩]+', '', line)
        line = re.sub(r'^[\-\*\.\·]+', '', line)
        line = re.sub(r'^\*\*', '', line)
        line = re.sub(r'\*\*$', '', line)
        line = re.sub(r'[\U00010000-\U0010ffff]', '', line)  # 移除 emoji
        return line.strip()

    def generate_ai_reply(self, message: str, relation: str, style: str,
                          conversation_history: str = "") -> Tuple[Optional[List[str]], str]:
        """生成 AI 增强回复"""
        if not self.api_key:
            return None, "无 API Key"

        try:
            import requests

            tone_guide = {
                "恋人": "甜蜜亲密，体现关心和爱意",
                "朋友": "自然轻松，幽默风趣",
                "同事": "专业礼貌，保持适当距离",
                "客户": "商务专业，稳妥可靠",
                "家人": "亲情温暖，体贴关怀",
                "追求者": "委婉得体，不伤害对方",
                "海王": "保持暧昧，欲拒还迎",
                "高冷": "简洁冷淡，爱搭不理"
            }
            guide = tone_guide.get(relation, "自然得体")

            style_prompt = {
                "稳妥版": "稳重得体，不过不失",
                "轻松版": "轻松自然，幽默俏皮",
                "升温版": "热情主动，增进感情"
            }
            style_desc = style_prompt.get(style, "")

            system_prompt = (f"你是微信聊天高手，关系{relation}，语气{guide}，回复风格{style_desc}。"
                           f"只需要输出 3 条回复，每条 12-20 字，用句号分隔。不要解释，不要编号，不要任何其他内容。")

            url = "https://api.minimax.chat/v1/text/chatcompletion_v2"
            headers = {"Content-Type": "application/json", "Authorization": f"Bearer {self.api_key}"}
            data = {
                "model": "MiniMax-M2.7",
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": f"对方说：{message}\n请直接给出 3 条回复，用句号分隔："}
                ],
                "max_tokens": 150
            }

            resp = requests.post(url, headers=headers, json=data, timeout=30)

            if resp.status_code != 200:
                return None, f"API 错误：{resp.status_code}"

            result = resp.json()
            api_msg = result.get("choices", [{}])[0].get("message", {})
            content = api_msg.get("content", "") or api_msg.get("reasoning_content", "")

            if not content:
                return None, "API 返回为空"

            self._log(f"AI 原始返回：{content[:100]}...")

            replies = self._parse_ai_response(content)

            if len(replies) >= 2:
                return replies[:3], f"[AI 模式] 解析到{len(replies)}条"
            else:
                return None, f"AI 解析失败 (仅{len(replies)}条)"

        except ImportError:
            return None, "缺少 requests 库"
        except Exception as e:
            return None, f"AI 错误：{str(e)}"

    def generate(self, message: str, relation: str, style: str = "稳妥版",
                 mode: str = "hybrid", conversation_history: str = "") -> Tuple[List[str], str]:
        """综合生成回复（本地+AI 混合模式）"""
        # 优先尝试 AI 模式
        if mode in ("hybrid", "ai") and self.api_key:
            replies, info = self.generate_ai_reply(message, relation, style, conversation_history)
            if replies:
                return replies, info

        # 降级到本地模式
        replies, info = self.generate_local_reply(message, relation, style)
        return replies, info
